const consentVersion = '2026-09-23';

/// 동의 항목 하나.
class ConsentItem {
  const ConsentItem({
    required this.key,
    required this.label,
    required this.required,
    required this.summary,
    required this.body,
    this.version = consentVersion,
  });

  /// 서버가 준 한 항목을 읽는다. 형식이 어긋나면 null이라 캐시·기본값으로 떨어진다.
  static ConsentItem? tryParse(Object? raw) {
    if (raw is! Map) return null;
    final key = raw['key'];
    final body = raw['body'];
    if (key is! String || key.isEmpty) return null;
    if (body is! String || body.trim().isEmpty) return null;
    return ConsentItem(
      key: key,
      label: raw['label'] is String ? raw['label'] as String : key,
      required: raw['required'] == true,
      summary: raw['summary'] is String ? raw['summary'] as String : '',
      body: body,
      version: raw['version'] is String ? raw['version'] as String : '',
    );
  }

  Map<String, dynamic> toJson() => {
    'key': key,
    'label': label,
    'required': required,
    'summary': summary,
    'body': body,
    'version': version,
  };

  /// 서버 요청 필드명과 같다.
  final String key;

  final String label;

  /// 필수 항목은 하나라도 빠지면 서비스를 쓸 수 없다.
  final bool required;

  /// 목록에서 보여줄 한 줄 요약.
  final String summary;

  /// 전문.
  final String body;

  /// 이 문서의 버전. 동의를 기록할 때 **실제로 보여준 것**을 보내야 한다.
  final String version;
}

