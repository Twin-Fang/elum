-- 카드 그림을 가리키는 값을 "경로"에서 "열쇠"로 바꾼다 (이슈 #251).
--
-- 지금까지는 저장 경로가 통째로 들어 있었다.
--
--     data/routine-images/{batchId}/1.png
--
-- 이러면 그림을 다른 곳에 두기로 하는 순간 이 값이 전부 죽는다 — 과거 카드의 그림이
-- 통째로 사라진다는 뜻이다. 저장 위치를 빼고 열쇠만 남기면, 파일을 옮기고 연결을
-- 갈아끼우는 것으로 끝난다.
--
--     {batchId}/1.png
--
-- 마지막 두 조각만 남긴다. 저장 폴더 설정이 환경마다 다르고 절대 경로일 수도 있어,
-- 특정 접두사를 지우는 방식으로는 환경에 따라 빗나간다.
--
-- 이미 열쇠 형태(슬래시 하나)인 행은 조건에 걸리지 않는다 — 다시 돌려도 안전하다.
update routine_step
set image_path = regexp_replace(image_path, '^.*/([^/]+/[^/]+)$', '\1')
where image_path is not null
  and image_path ~ '^.*/[^/]+/[^/]+$';
