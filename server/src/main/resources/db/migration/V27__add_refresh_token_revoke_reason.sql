-- 리프레시 토큰 폐기 사유 (이슈 #360 D1).
--
-- 끊긴 토큰이 다시 오면 지금은 전부 "복사본 재사용(탈취)"으로 보고 그 보호자의 다른 휴대폰까지 끊는다.
-- 로그아웃으로 끊긴 토큰과 회전으로 끊긴 토큰을 가를 값이 없어서다. 이 컬럼이 그 값이다.
-- 재사용 감지(세션 전부 끊기)는 ROTATED 로 끊긴 토큰에만 적용한다.
--
-- 추가만 한다. 비워 둘 수 있는 컬럼이라 옛 서버 이미지로 되돌려도 옛 코드는 이 컬럼을 모르고 그대로 돈다
-- (Flyway 는 스키마를 되돌리지 않는다, V25·V26 과 같은 약속).
--
-- 기존 행은 채우지 않는다(NULL = 사유 모름). 회전인지 로그아웃인지 알 수 없는 토큰으로 세션을 전부 끊으면
-- D1 이 그대로 남으므로, 코드는 NULL 을 "401 만" 으로 다룬다. 끊긴 토큰은 어차피 쓸 수 없고,
-- 잃는 것은 V27 이전에 회전된 토큰의 탈취 감지뿐이다.
--
-- 로컬(ddl-auto: update)에서 이미 만들어졌을 수 있어 if not exists 로 양쪽 모두 안전하게 한다.
alter table refresh_token add column if not exists revoke_reason varchar(30);
